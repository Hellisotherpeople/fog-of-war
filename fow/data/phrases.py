def lang(nation: str) -> str:
    return LANG.get(nation, "en")


def phrase(rng, nation: str, key: str) -> str:
    t = P.get(key, {})
    lst = t.get(lang(nation)) or t.get("en") or ["!"]
    return rng.choice(lst)


def all_lines(nation: str):
    """Every fixed line this army might say (for warming up the voice cache)."""
    lg = lang(nation)
    out = []
    for t in P.values():
        out += t.get(lg) or t.get("en") or []
    return out
